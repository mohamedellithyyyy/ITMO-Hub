    p.ИД,
    e.ЧЛВК_ИД,
    s.ЧЛВК_ИД
FROM Н_УЧЕНИКИ s
JOIN Н_ОБУЧЕНИЯ e 
    ON e.ЧЛВК_ИД = s.ЧЛВК_ИД
JOIN Н_ЛЮДИ p 
    ON p.ИД = e.ЧЛВК_ИД
WHERE 
    p.ОТЧЕСТВО > 'Сергеевич'
    AND e.ЧЛВК_ИД > 105590
    AND s.ИД < 150308;
